"""Single source of truth for the database schema settings (MIG-1, D3).

`env.py` (Alembic) and the drift-guard test both use `MIGRATE_OPTIONS`, so
"what a migration considers" and "what the test compares" can never diverge.
"""
SCHEMA = 'riftbound'


def include_name(name, type_, parent_names):
    """Alembic `include_name` hook: only schema `riftbound` is ever reflected.

    With `include_schemas=True` Alembic asks about every schema it can see.
    The default schema (`public` on PostgreSQL, `main` on SQLite) arrives as
    `None` and is refused, so nothing outside `riftbound` is compared,
    autogenerated or dropped. Objects inside an accepted schema are all kept.
    """
    if type_ == 'schema':
        return name == SCHEMA
    return True


MIGRATE_OPTIONS = dict(
    version_table_schema=SCHEMA,
    include_schemas=True,
    compare_type=True,
    include_name=include_name,
)
